// Level & XP formulas
export const XP_PER_LEVEL = 200;

export function getLevelForXP(xp: number): { level: number; currentXP: number; nextLevelXP: number; progressPct: number; title: string } {
  let level = 1;
  let remaining = xp;
  let needed = XP_PER_LEVEL;

  while (remaining >= needed && level < 50) {
    remaining -= needed;
    level++;
    needed = Math.round(XP_PER_LEVEL * Math.pow(1.1, level - 1));
  }

  const titles = [
    'Novice Drifter',
    'Street Courier',
    'Rooftop Skater',
    'Shadow Stalker',
    'Kinetic Sprinter',
    'Apex Runner',
    'Speed Specialist',
    'Chrono Dasher',
    'Ghost Operator',
    'Void Walker',
    'Spire Sovereign',
    'Transcendent Master',
  ];

  const titleIndex = Math.min(titles.length - 1, Math.floor((level - 1) / 4));
  const progressPct = Math.min(100, Math.round((remaining / needed) * 100));
  return {
    level,
    currentXP: remaining,
    nextLevelXP: needed,
    progressPct,
    title: titles[titleIndex],
  };
}

